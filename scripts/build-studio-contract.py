"""Generate consumer types from Pydantic's HTTP JSON Schema, never a second schema."""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'backend'))
from app import schemas_studio as s
from app import schemas_quality as q
from app import schemas_studio_voice as v
names=['StudioProductReferencePlan','PipelineStart','DecisionInput','ComposeInput','StudioProject','StudioDecision','StudioShot','StudioOverview','ComposeResult',
       'ShotFramingTarget','ShotFramingUpdate','ShotFramingRow','ShotFramingOverview','ShotFramingResult']
schemas={name:getattr(s,name).model_json_schema() for name in names}
def ts(schema):
    if '$ref' in schema:return schema['$ref'].split('/')[-1]
    if 'anyOf' in schema:return ' | '.join(ts(i) for i in schema['anyOf'])
    if 'enum' in schema:return ' | '.join(json.dumps(v) for v in schema['enum'])
    kind=schema.get('type')
    if kind=='array':return '('+ts(schema.get('items',{}))+')[]'
    if kind=='object':return 'Record<string, any>'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'any')
output=['// Generated by scripts/build-studio-contract.py. Edit schemas_studio.py.', 'import type { QualitySettings } from "./quality-contract";']
for name,schema in schemas.items():
    fields=[]
    for key,value in schema['properties'].items():fields.append('  '+key+('' if key in schema.get('required',[]) else '?')+': '+ts(value)+';')
    output.append('export interface '+name+' {\n'+'\n'.join(fields)+'\n}')
(ROOT/'schemas/studio-http.schema.json').write_text(json.dumps(schemas,ensure_ascii=False,indent=2),'utf-8')
(ROOT/'frontend/src/lib/studio-contract.ts').write_text('\n\n'.join(output)+'\n','utf-8')
